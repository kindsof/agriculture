def load_pool() -> dict[str, list[dict]]:
    pool: dict[str, list[dict]] = {}
    for name in POOLS:
        path = ROOT / name
        if not path.exists():
            continue
        for key, items in json.loads(path.read_text(encoding="utf-8")).items():
            for item in items or []:
                url = item.get("url", "")
                host = url.split("/")[2] if "://" in url else ""
                if not any(host == t or host.endswith("." + t) for t in TRUSTED):
                    continue
                bucket = pool.setdefault(key, [])
                seen = next((s for s in bucket if s["url"] == url), None)
                if seen is None:
                    if url:
                        bucket.append(item)
                elif len(item.get("title") or "") > len(seen.get("title") or ""):
                    # 同一 URL 在多个池里出现时先到先占坑，会把更准确的标题静默丢掉
                    # （机器抓的 <title> 常只是机构名，人工补的标题才带条目名，
                    # 而 choose() 正是靠标题里的条目名放行的）。留信息量更大的那个。
                    seen["title"] = item["title"]
    for items in pool.values():
        items.sort(key=lambda s: TRUSTED.index(
            next((t for t in TRUSTED
                  if s["url"].split("/")[2].endswith(t)), TRUSTED[-1])))
    return pool


def choose(pool, key: str, name: str, must: str) -> list[dict]:
    # Both the full entry name and the short keyword must appear in the title:
    # a gate on the practice word alone let 「寮步香市」(东莞) pass as the source
    # for 「乌镇香市」(浙江) — same word, different province, wrong citation.
    picked = [s for s in pool.get(key, [])
              if must in (s.get("title") or "")
              and name in (s.get("title") or "")]
    if not picked:
        return []
    return picked[:2]


def block(entry, kind: str, sources: list[dict]) -> str:
    (eid, name, province, city, lng, lat, summary, culture,
     heritage, tags, _key, _must) = entry
    lines = [
        f"  - id: {eid}",
        f"    name: {name}",
        f"    category: {kind}",
        f"    province: {province}",
        f"    city: {city}",
        f"    lng: {lng:.2f}",
        f"    lat: {lat:.2f}",
        "    summary: >-",
        f"      {summary}",
        "    culture: >-",
        f"      {culture}",
        "    heritage:",
    ]
    lines += [f"      - {h}" for h in heritage]
    lines.append("    tags: [" + ", ".join(tags) + "]")
    lines.append("    sources:")
    for s in sources:
        title = s["title"].replace('"', "")
        lines.append(f"      - title: {title}")
        lines.append(f"        url: {s['url']}")
    return "\n".join(lines) + "\n"


def main() -> int:
    pool = load_pool()
    out, missing = [], []
    for entry, kind in PLACES:
        sources = choose(pool, entry[10], entry[1], entry[11])
        if not sources:
            missing.append(f"{entry[0]} (须含「{entry[11]}」的已验证来源)")
            continue
        out.append(block(entry, kind, sources))
    # Idempotent: re-running must not append a site that is already in the file.
    # (An accidental double run once appended 35 duplicates behind build_data's
    # back; build_data catches duplicate ids, but the generator should not make
    # them in the first place.)
    existing = set(re.findall(r"^\s*-\s*id:\s*(\S+)", SITES.read_text(encoding="utf-8"), re.M))
    fresh = [b for b in out if not any(b.lstrip().startswith(f"- id: {i}") for i in existing)]
    redone = len(out) - len(fresh)
    out = fresh
    text = SITES.read_text(encoding="utf-8").rstrip("\n") + "\n"
    for chunk in out:
        text += "\n" + chunk
    SITES.write_text(text, encoding="utf-8")
    print(f"appended {len(out)} sites to {SITES.relative_to(ROOT.parent)}" + (f"（跳过已在仓内 {redone} 条）" if redone else ""))
    if missing:
        print("skipped for lack of a verified source:")
        for m in missing:
            print("  - " + m)
    return 0


if __name__ == "__main__":
    sys.exit(main())
